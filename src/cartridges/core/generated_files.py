"""The files a cherry-pick conflict may be resolved by regenerating, and how to regenerate each.

The lander (`agent_tools.land`) resolves with these; the decompose graph adds each to a task's surfaces when its
generator source is one. Declared, not guessed from names.
"""

from __future__ import annotations

from typing import NamedTuple

# The markers around the README's generated Commands block; `agent_tools.readme_commands` writes between them.
README_BEGIN = "<!-- commands:begin (generated by `python -m devtools commands render`; do not edit) -->"
README_END = "<!-- commands:end -->"


class GeneratedFile(NamedTuple):
    """How to regenerate one file: the directory to run in, the `python` arguments that rewrite the file given
    its path as a last argument, and the markers around the span the generator owns."""

    cwd: str
    command: tuple[str, ...]
    begin: str
    end: str
    sources: tuple[str, ...] = ()


# Each repo-relative path mapped to its generator. The README's generator is `python -m agent_tools.readme_commands`,
# the one `test_readme_commands` compares the README against.
GENERATED_FILES: dict[str, GeneratedFile] = {
    "src/tools/README.md": GeneratedFile(
        "src/tools",
        ("-m", "agent_tools.readme_commands", "--readme"),
        README_BEGIN,
        README_END,
        ("src/tools/agent_tools/cli.py", "src/tools/agent_tools/readme_commands.py"),
    ),
}
